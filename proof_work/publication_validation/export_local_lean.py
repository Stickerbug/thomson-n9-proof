"""Export exact local LDL data; proves endpoint arithmetic, not Hessian binding.

No native_decide, float arithmetic, or asserted real factorization.  --check
compares generated Lean and manifest byte-for-byte. --self-test checks that
invalid certificate shapes/signs are rejected before emission.
"""
from pathlib import Path
from fractions import Fraction as Q
from hashlib import sha256
from copy import deepcopy
import argparse
import json

BASE = Path(__file__).resolve().parent
OUT = BASE / 'formal/ThomsonNine/LocalLDLData.lean'
MANIFEST = BASE / 'local_lean_export_manifest.json'
LABELS = ['AAA', 'CBA', 'CCA', 'AFF', 'GAF', 'BFF', 'GGB', 'CFF', 'CGF', 'DDD', 'DFF', 'GDF']
BOUNDARY = {6, 7, 9}


def need(ok, msg):
    if not ok:
        raise ValueError(msg)


def interval(v):
    need(isinstance(v, list) and len(v) == 2, 'interval shape')
    lo, hi = map(Q, v)
    need(lo <= hi, 'reversed interval')
    return lo, hi


def validate(row, index):
    n = 2 if index in BOUNDARY else 3
    need(row['row_index'] == index and ''.join(row['labels']) == LABELS[index], 'row identity')
    kind = ('lower_Gram_graph_monotonicity_and_boundary_Hessian_PD' if n == 2
            else 'interior_Hessian_PD_on_convex_cube')
    need(row['kind'] == kind, 'row kind')
    need(row['status'] == 'INDEPENDENT_LOCAL_FULL_SOURCEBOX_ARITHMETIC_PASS', 'row status')
    need(len(row['LDL_pivots']) == n, 'pivot dimension')
    for v in row['LDL_pivots']:
        need(interval(v)[0] > 0, 'nonpositive pivot')
    L = row['LDL_L']
    W = row['congruence_W']
    V = row['W_inverse']
    for M in [L, W, V]:
        need(len(M) == n and all(len(r) == n for r in M), 'matrix dimension')
    for i in range(n):
        for j in range(n):
            interval(L[i][j])
            if i <= j:
                need(interval(L[i][j]) == (Q(i == j), Q(i == j)), 'L not unit lower')
                need(Q(W[i][j]) == int(i == j), 'W not unit lower')
            need(sum(Q(W[i][k]) * Q(V[k][j]) for k in range(n)) == int(i == j), 'W inverse mismatch')
    need(len(row['sourcebox']) == 3 and len(row['new_center_intervals']) == 3, 'box dimension')
    for domain, center in zip(row['sourcebox'], row['new_center_intervals']):
        lo, hi = interval(domain)
        cl, ch = interval(center)
        need(lo <= cl <= ch <= hi, 'center outside sourcebox')
    if n == 2:
        need(interval(row['R_gradient_on_expanded_hull'][0])[0] > 0, 'nonpositive boundary R_u')
    return n


def rat(q):
    q = Q(q)
    return f'({q.numerator} : ℚ)' if q.denominator == 1 else f'({q.numerator} / {q.denominator} : ℚ)'


def lean_interval(v):
    lo, hi = interval(v)
    return f'⟨{rat(lo)}, {rat(hi)}, by norm_num⟩'


def render(rows, sources):
    lines = ['import ThomsonNine.LocalLDLSemantics', '',
             '/-! Generated by export_local_lean.py from hash-checked independent rows.',
             'Only rational interval ordering, pivot positivity and box containment are proved.',
             'Hessian evaluation, real LDL membership, exact contacts and local function',
             'nonnegativity are NOT asserted here. See local_lean_export_manifest.json. -/', '',
             'namespace ThomsonNine.LocalLDL.Data', '', 'open ThomsonNine.Interval', '']
    stats = []
    for i, row in enumerate(rows):
        n = validate(row, i)
        name = f'cert_{i:02d}_{LABELS[i]}'
        lines += [f'/-- {LABELS[i]}: {n} by {n} LDL data. Source SHA-256: {sources[i]["sha256"]}. -/',
                  f'def {name} : LDL{n}Cert where']
        for k in range(n):
            lines += [f'  d{k+1} := {lean_interval(row["LDL_pivots"][k])}']
        for a in range(1, n):
            for b in range(a):
                lines += [f'  l{a+1}{b+1} := {lean_interval(row["LDL_L"][a][b])}']
        for a in range(1, n):
            for b in range(a):
                lines += [f'  w{a+1}{b+1} := {rat(row["congruence_W"][a][b])}']
        for k in range(n):
            lines += [f'  hd{k+1} := by norm_num']
        lines += ['']
        for j in range(3):
            lines += [f'def box_{i:02d}_{j} : RatInterval := {lean_interval(row["sourcebox"][j])}',
                      f'def center_{i:02d}_{j} : RatInterval := {lean_interval(row["new_center_intervals"][j])}',
                      f'theorem center_contained_{i:02d}_{j} :',
                      f'    box_{i:02d}_{j}.lo ≤ center_{i:02d}_{j}.lo ∧ center_{i:02d}_{j}.hi ≤ box_{i:02d}_{j}.hi := by',
                      f'  norm_num [box_{i:02d}_{j}, center_{i:02d}_{j}]', '']
        if n == 2:
            lines += [f'def boundary_Ru_{i:02d} : RatInterval := {lean_interval(row["R_gradient_on_expanded_hull"][0])}',
                      f'theorem boundary_Ru_pos_{i:02d} : 0 < boundary_Ru_{i:02d}.lo := by',
                      f'  norm_num [boundary_Ru_{i:02d}]', '']
        stats.append({'index': i, 'labels': LABELS[i], 'dimension': n, 'lean_definition': name,
                      'source_file': sources[i]['file'], 'source_sha256': sources[i]['sha256'],
                      'pivot_lower': [str(interval(v)[0]) for v in row['LDL_pivots']]})
    lines += ['end ThomsonNine.LocalLDL.Data', '']
    text = '\n'.join(lines)
    manifest = {'status': 'EXACT_LOCAL_DATA_EXPORT_ONLY', 'rows': stats,
                'interior_count': 9, 'boundary_count': 3, 'pivot_count': 33,
                'center_containment_theorems': 36, 'boundary_Ru_positive_theorems': 3,
                'generated_lean': str(OUT.relative_to(BASE)),
                'generated_lean_sha256': sha256(text.encode()).hexdigest(),
                'exporter_sha256': sha256(Path(__file__).read_bytes()).hexdigest(),
                'unproved_bridges': ['real Hessian interval evaluation over each box',
                    'LDL pivot memberships for every real Hessian', 'P = W H W^T and P = L D L^T',
                    'exact contact values and gradients', 'boundary graph chain rule and monotonicity',
                    'Hessian positivity to residual nonnegativity', 'concrete tree terminal bindings']}
    return text, json.dumps(manifest, indent=2, ensure_ascii=False) + '\n'


def load():
    summary = json.loads((BASE / 'independent_local_arithmetic_result.json').read_bytes())
    need(summary['status'] == 'INDEPENDENT_TWELVE_LOCAL_ARITHMETIC_PASS_CONDITIONAL_ON_EXACT_CONTACTS', 'summary status')
    need(set(summary['rows']) == {str(i) for i in range(12)}, 'summary coverage')
    for name, digest in summary['source_sha256'].items():
        path = BASE.parent / name if name.startswith('d10_') else BASE / name
        need(sha256(path.read_bytes()).hexdigest() == digest, 'source hash mismatch: ' + name)
    rows, sources = [], []
    for i in range(12):
        entry = summary['rows'][str(i)]
        name = f'independent_local_{i:02d}_{LABELS[i]}.json'
        need(entry['file'] == name, 'unexpected row file')
        raw = (BASE / name).read_bytes()
        need(sha256(raw).hexdigest() == entry['sha256'], 'row hash mismatch: ' + name)
        row = json.loads(raw)
        need(row['source_bindings'] == summary['source_sha256'], 'row source bindings mismatch')
        validate(row, i)
        rows.append(row)
        sources.append({'file': name, 'sha256': entry['sha256']})
    return rows, sources


def self_test(rows):
    mutations = [
        (0, lambda r: r['LDL_pivots'][0].__setitem__(0, '0')),
        (0, lambda r: r['LDL_pivots'][0].__setitem__(0, '-1')),
        (0, lambda r: r['LDL_pivots'].pop()),
        (0, lambda r: r['congruence_W'][0].__setitem__(1, '1')),
        (0, lambda r: r['W_inverse'][0].__setitem__(0, '2')),
        (0, lambda r: r['LDL_L'][0].__setitem__(0, ['0', '0'])),
        (0, lambda r: r.__setitem__('row_index', 1)),
        (0, lambda r: r.__setitem__('kind', 'unknown')),
        (0, lambda r: r.__setitem__('status', 'FAIL')),
        (0, lambda r: r['sourcebox'].__setitem__(0, ['0', '0'])),
        (6, lambda r: r['R_gradient_on_expanded_hull'][0].__setitem__(0, '0')),
        (6, lambda r: r['LDL_pivots'].__setitem__(0, ['2', '1'])),
    ]
    for index, mutate in mutations:
        bad = deepcopy(rows[index])
        mutate(bad)
        try:
            validate(bad, index)
        except ValueError:
            continue
        raise AssertionError('negative test was accepted')
    print(f'EXPORT_NEGATIVE_TESTS_PASS {len(mutations)}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--self-test', action='store_true')
    args = parser.parse_args()
    rows, sources = load()
    text, manifest = render(rows, sources)
    if args.self_test:
        self_test(rows)
    if args.check:
        need(OUT.read_text() == text, 'generated Lean differs')
        need(MANIFEST.read_text() == manifest, 'manifest differs')
        print('LOCAL_LEAN_EXPORT_CHECK_PASS: 12 rows, 33 pivots, 36 center containments')
    else:
        # Paths are fixed above; this is deterministic generation, no source artifact changes.
        OUT.write_text(text)
        MANIFEST.write_text(manifest)
        print('LOCAL_LEAN_EXPORT_WRITTEN: 12 rows, 33 pivots, 36 center containments')


if __name__ == '__main__':
    main()
